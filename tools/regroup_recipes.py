def classify(name, text):
    for hay in (name.lower(), text.lower()):
        for cat, sub, kws in RULES:
            if kws and any(k in hay for k in kws):
                return cat, sub
    return "Дім і затишок", "Інше вдома"


def parse(text):
    blocks, cur = [], None
    for ln in text.split("\n"):
        m = re.match(r"^\[([^\]]+)\]\s+(.+)$", ln)
        if m:
            cur = {"key": m.group(1), "name": m.group(2).strip(), "z": None, "what": "", "extra": []}
            blocks.append(cur); continue
        if cur is None or not ln.strip() or ln.startswith("#"):
            continue
        if ln.startswith("з:"):
            cur["z"] = [[a.strip() for a in ing.split("|") if a.strip()] for ing in ln[2:].split("·")]
        elif ln.startswith("потрібно нове:"):
            continue
        elif not cur["what"]:
            cur["what"] = ln.strip()
        else:
            cur["extra"].append(ln.strip())
    return blocks


def main():
    dry = "--dry" in sys.argv
    blocks = parse(io.open(PATH, encoding="utf-8").read())
    # дублікати за набором складників (усі варіанти) і за першими варіантами
    keep, seen_all, seen_first, remap = [], {}, {}, {}
    for b in blocks:
        s_all = frozenset(frozenset(g) for g in b["z"])
        s_first = frozenset(g[0] for g in b["z"])
        prev = seen_all.get(s_all) or seen_first.get(s_first)
        if prev:
            remap[b["name"]] = prev["name"]; continue
        seen_all[s_all] = b; seen_first[s_first] = b; keep.append(b)
    # посилання на прибрані рецепти -> на ті, що лишились
    for b in keep:
        b["z"] = [list(dict.fromkeys(remap.get(a, a) for a in g)) for g in b["z"]]
    # класифікація
    for b in keep:
        text = b["what"] + " " + " ".join(a for g in b["z"] for a in g)
        b["cat"], b["sub"] = classify(b["name"], text)
    dist = collections.defaultdict(collections.Counter)
    for b in keep:
        dist[b["cat"]][b["sub"]] += 1
    print("було:", len(blocks), "| прибрано дублікатів:", len(blocks) - len(keep), "| лишилось:", len(keep))
    for cat in CAT_ORDER:
        subs = dist.get(cat, {})
        print("%s (%d): %s" % (cat, sum(subs.values()), ", ".join("%s %d" % kv for kv in sorted(subs.items(), key=lambda x: -x[1]))))
    if dry:
        fb = [b["name"] for b in keep if b["sub"] == "Інше вдома"]
        print("у запасному «Дім»:", len(fb), fb[:30])
        for cat in CAT_ORDER:
            for sub in dist.get(cat, {}):
                names = [b["name"] for b in keep if b["cat"] == cat and b["sub"] == sub][:4]
                print("   ", cat, "/", sub, ":", " · ".join(names))
        return
    out = HEAD
    for cat in CAT_ORDER:
        items = [b for b in keep if b["cat"] == cat]
        if not items:
            continue
        out += "\n## %s\n" % cat
        subs = [s for c, s, _kw in RULES if c == cat]
        seen = set()
        for sub in subs:
            if sub in seen:
                continue
            seen.add(sub)
            group = [b for b in items if b["sub"] == sub]
            if not group:
                continue
            out += "\n### %s\n" % sub
            for b in group:
                out += "\n[%s] %s\nз: %s\n%s\n" % (b["key"], b["name"],
                                                 " · ".join(" | ".join(g) for g in b["z"]), b["what"])
                for e in b["extra"]:
                    out += e + "\n"
    io.open(PATH, "w", encoding="utf-8").write(out)
    print("записано:", len(keep), "рецептів")


if __name__ == "__main__":
    main()
